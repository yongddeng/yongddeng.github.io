// ---- 203. expected value ----

// one positive X on Ω = [0, 1) for both figures, sampled at M midpoints, so a mean is an integral
const M = 4096;
const X = w => 0.6 + 2.2 * w * w - 1.6 * w * w * w + 0.45 * Math.sin(9 * w);
const xs = Float64Array.from({ length: M }, (_, i) => X((i + 0.5) / M));
const mean = a => a.reduce((s, v) => s + v, 0) / a.length;
const EX = mean(xs);
// the average of X over each of k equal cells, spread back over the cells
const cellAverage = (a, k) => {
	const out = new Float64Array(M);
	for (let j = 0; j < k; j++) {
		const lo = j * M / k, hi = (j + 1) * M / k;
		let s = 0;
		for (let i = lo; i < hi; i++) s += a[i];
		out.fill(s / (hi - lo), lo, hi);
	}
	return out;
};
// a function on the M midpoints as pixel pairs
const trace = (P, a) => {
	const pts = [];
	for (let px = P.x0; px <= P.x1; px++) pts.push([px, P.Y(a[Math.min(M - 1, Math.floor(P.x(px) * M))])]);
	return pts;
};
const axes = (c, P) => {
	frameBox(c, P);
	for (const v of [0, 0.5, 1, 1.5]) label(c, String(v), P.x0 - 5, P.Y(v) + 4, 'right');
	label(c, '0', P.x0, P.y0 + 13, 'center');
	label(c, 'ω', (P.x0 + P.x1) / 2, P.y0 + 13, 'center');
	label(c, '1', P.x1, P.y0 + 13, 'center');
};

// simple functions under X, cutting the range (Lebesgue) or the domain (Riemann)
FIGS['203/simple'] = el => {
	const W = 460, H = 200;
	const P = plotBox(34, 446, 180, 22, [0, 1], [0, 1.8]);
	const c = canvas(el, W, H);
	const row = figRow(el);
	let lebesgue = true, n = 3;
	function approx() {
		if (lebesgue) return xs.map(v => Math.min(n, Math.floor(v * 2 ** n) / 2 ** n));
		// the infimum of X on each of 2ⁿ cells
		const k = 2 ** n, out = new Float64Array(M);
		for (let j = 0; j < k; j++) {
			const lo = j * M / k, hi = (j + 1) * M / k;
			let m = Infinity;
			for (let i = lo; i < hi; i++) m = Math.min(m, xs[i]);
			out.fill(m, lo, hi);
		}
		return out;
	}
	function draw() {
		const s = approx();
		clear(c);
		// the cuts, levels across or cells along, while they stay apart
		c.strokeStyle = COL.grid;
		c.lineWidth = 1;
		if (lebesgue && P.Y(0) - P.Y(2 ** -n) >= 3) {
			for (let v = 2 ** -n; v < 1.8; v += 2 ** -n) polyline(c, [[P.x0, Math.round(P.Y(v)) + 0.5], [P.x1, Math.round(P.Y(v)) + 0.5]]);
		} else if (!lebesgue && (P.x1 - P.x0) / 2 ** n >= 3) {
			for (let j = 1; j < 2 ** n; j++) polyline(c, [[Math.round(P.X(j / 2 ** n)) + 0.5, P.y1], [Math.round(P.X(j / 2 ** n)) + 0.5, P.y0]]);
		}
		// the simple function as an area, then X over it
		const top = trace(P, s);
		c.fillStyle = 'rgba(0, 0, 128, 0.16)';
		c.beginPath();
		c.moveTo(P.x0, P.y0);
		top.forEach(([x, y]) => c.lineTo(x, y));
		c.lineTo(P.x1, P.y0);
		c.closePath();
		c.fill();
		c.strokeStyle = COL.ink;
		c.lineWidth = 1.2;
		polyline(c, top);
		c.strokeStyle = COL.black;
		c.lineWidth = 1.6;
		polyline(c, trace(P, xs));
		axes(c, P);
		label(c, lebesgue ? 'Xₙ = min(n, 2⁻ⁿ⌊2ⁿX⌋), the range cut into levels' : 'the infimum of X on each of 2ⁿ cells of Ω', P.x0, 14, 'left', COL.ink);
		label(c, 'X', P.X(0.86), P.Y(1.66) - 5, 'center', COL.black);
		readEl.textContent = `E Xₙ = ${mean(s).toFixed(3)} ↑ E X = ${EX.toFixed(3)}`;
	}
	const btn = button(row, 'Cut Ω', () => {
		lebesgue = !lebesgue;
		btn.textContent = lebesgue ? 'Cut Ω' : 'Cut range';
		draw();
	});
	slider(row, 'n', 1, 7, n, v => { n = v; draw(); });
	const readEl = reading(row);
	draw();
};

// E(X | 𝒢) for 𝒢 generated by 2ʲ equal cells, with the next coarser one dashed
FIGS['203/condexp'] = el => {
	const W = 460, H = 200;
	const P = plotBox(34, 446, 180, 22, [0, 1], [0, 1.8]);
	const c = canvas(el, W, H);
	const row = figRow(el);
	function draw(j) {
		const fine = cellAverage(xs, 2 ** j);
		clear(c);
		c.strokeStyle = COL.grid;
		c.lineWidth = 1;
		for (let i = 1; i < 2 ** j; i++) polyline(c, [[Math.round(P.X(i / 2 ** j)) + 0.5, P.y1], [Math.round(P.X(i / 2 ** j)) + 0.5, P.y0]]);
		c.strokeStyle = COL.black;
		c.lineWidth = 1.2;
		polyline(c, trace(P, xs));
		if (j > 0) {
			c.strokeStyle = COL.tail;
			c.lineWidth = 1.6;
			c.setLineDash([5, 3]);
			polyline(c, trace(P, cellAverage(xs, 2 ** (j - 1))));
			c.setLineDash([]);
		}
		c.strokeStyle = COL.ink;
		c.lineWidth = 2;
		polyline(c, trace(P, fine));
		axes(c, P);
		label(c, 'E(X | 𝒢), the average on each cell', P.x0, 14, 'left', COL.ink);
		if (j > 0) label(c, 'one level coarser', P.x1, 14, 'right', COL.tail);
		// its mean stays E X, and its L² distance to X shrinks as 𝒢 grows
		let d = 0;
		for (let i = 0; i < M; i++) d += (xs[i] - fine[i]) ** 2;
		readEl.textContent = `mean ${mean(fine).toFixed(3)} · ‖X − E(X | 𝒢)‖₂ = ${Math.sqrt(d / M).toFixed(3)}`;
	}
	slider(row, 'j', 0, 6, 2, draw, { show: v => `${2 ** v} cells` });
	const readEl = reading(row);
	draw(2);
};

// Ω = {ω₁, ω₂, ω₃} with P uniform, so a random variable is a point of ℝ³ and
// E(XY) is a third of the dot product, orthogonal in one meaning orthogonal in
// the other. L²(𝒢) for 𝒢 generated by two cells is a plane through 0, the
// constants a line inside it, and E(X | 𝒢) the foot of the perpendicular from X
FIGS['203/proj'] = el => {
	const W = 460, H = 250;
	const CELLS = { '12 | 3': [[0, 1], [2]], '1 | 23': [[0], [1, 2]], '13 | 2': [[0, 2], [1]] };
	// how far the plane and the line of constants are drawn
	const LO = -0.4, HI = 1.6;
	const c = canvas(el, W, H);
	const row = figRow(el);
	const view = view3d(c, { W, H, scale: 80, yaw: 0.2, pitch: 0.35, centre: [0.55, 0.55, 0.45] }, draw);
	let cells, seed = 4, x;
	const ms = (a, b) => a.reduce((s, ai, i) => s + (ai - b[i]) ** 2, 0) / 3;
	// E(X | 𝒢) averages X over each cell
	const condE = v => {
		const out = [0, 0, 0];
		for (const cell of cells) {
			const m = cell.reduce((s, i) => s + v[i], 0) / cell.length;
			for (const i of cell) out[i] = m;
		}
		return out;
	};
	function sample() {
		const u = rng(seed);
		x = [0, 1, 2].map(() => -0.4 + 2 * u());
	}
	function draw() {
		clear(c);
		// the plane L²(𝒢), spanned by the indicators of the two cells
		const [a, b] = cells.map(cell => [0, 1, 2].map(i => (cell.includes(i) ? 1 : 0)));
		const corner = (s, t) => a.map((ai, i) => s * ai + t * b[i]);
		c.fillStyle = 'rgba(0, 0, 128, 0.06)';
		c.beginPath();
		[corner(LO, LO), corner(HI, LO), corner(HI, HI), corner(LO, HI)].map(view.at).forEach(([px, py], i) => (i ? c.lineTo(px, py) : c.moveTo(px, py)));
		c.fill();
		for (let k = 0; k <= 4; k++) {
			const s = LO + (HI - LO) * k / 4;
			view.curve([corner(s, LO), corner(s, HI)], 'rgba(0, 0, 128, 0.2)', 0.8);
			view.curve([corner(LO, s), corner(HI, s)], 'rgba(0, 0, 128, 0.2)', 0.8);
		}
		// an axis for each outcome, and the line of constants
		['ω₁', 'ω₂', 'ω₃'].forEach((name, i) => {
			const e = [0, 0, 0];
			e[i] = 1.9;
			view.curve([[0, 0, 0], e], COL.frame, 1);
			const [px, py] = view.at(e);
			label(c, name, px + 4, py);
		});
		view.curve([[LO, LO, LO], [HI, HI, HI]], COL.black, 1);
		const G = condE(x), m = mean(x), E = [m, m, m];
		view.curve([[0, 0, 0], x], COL.ink, 2.2);
		c.setLineDash([4, 3]);
		view.curve([x, G], COL.ink, 1.2);
		view.curve([G, E], COL.tail, 1.2);
		view.curve([x, E], COL.mute, 1);
		c.setLineDash([]);
		// the right angle at E(X | 𝒢)
		const toward = p => {
			const d = p.map((pi, i) => pi - G[i]), r = Math.hypot(...d);
			return r > 0.05 ? d.map(q => q * 0.12 / r) : null;
		};
		const u = toward(x), w = toward(E);
		if (u && w) view.curve([G.map((g, i) => g + u[i]), G.map((g, i) => g + u[i] + w[i]), G.map((g, i) => g + w[i])], COL.mute, 1);
		for (const [p, colour, name, dx, dy, align] of [[x, COL.ink, 'X', 8, -6, 'left'], [G, COL.tail, 'E(X | 𝒢)', -8, 14, 'right'], [E, COL.black, 'E X', -8, -6, 'right']]) {
			const [px, py] = view.at(p);
			c.fillStyle = colour;
			dot(c, px, py, 3.5);
			label(c, name, px + dx, py + dy, align, colour);
		}
		// Pythagoras in the triangle X, E(X | 𝒢), E X is the law of total variance;
		// Var X shown as the sum of the parts as shown, so the three figures add up
		const within = ms(x, G).toFixed(3), between = ms(G, E).toFixed(3);
		label(c, `Var X ${(+within + +between).toFixed(3)} = E Var(X | 𝒢) ${within} + Var E(X | 𝒢) ${between}`, 10, 16, 'left', COL.black);
	}
	const pick = presets(row, Object.keys(CELLS).map(k => [k, k]), k => { cells = CELLS[k]; draw(); });
	button(row, 'Resample X', () => { seed += 1; sample(); draw(); });
	sample();
	pick('12 | 3');
};
